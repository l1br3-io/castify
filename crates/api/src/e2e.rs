    /// Sharing task 013: the embedded MPEG-2 fixture decodes, is a real
    /// MPEG program stream (pack-start code 0x000001BA), and is routed to
    /// `gd-concert` while every other id keeps the MP4 bytes. The
    /// codec-level claim (ffprobe reads mpeg2video → transcode strategy) is
    /// proven by the Playwright suite against the ffmpeg-capable e2e image,
    /// not here — unit tests must not require a system ffmpeg.
    #[test]
    fn mpeg2_fixture_decodes_and_routes_by_file_id() {
        let mpg = fixture_bytes("gd-concert");
        assert!(
            mpg.len() > 8_000,
            "fixture should be a real stream, got {} bytes",
            mpg.len()
        );
        assert_eq!(
            &mpg[0..4],
            &[0x00, 0x00, 0x01, 0xBA],
            "MPEG-PS pack start code"
        );
        assert_eq!(fixture_content_type("gd-concert"), "video/mpeg");

        let mp4 = fixture_bytes("gd-vacation");
        assert_eq!(&mp4[4..8], b"ftyp", "MP4 ftyp box for every other fixture");
        assert_eq!(fixture_content_type("gd-vacation"), "video/mp4");
    }

    /// M9 task 005: every provider's mock listing carries non-media files
    /// across all kinds and nested folders, alongside videos + subtitles.
    #[tokio::test]
    async fn mock_listing_carries_non_media_fixtures() {
        for provider in [Provider::GoogleDrive, Provider::Dropbox, Provider::OneDrive] {
            let factory = E2eMockFactory::new(provider);
            let provider_inst = factory
                .create(&TokenBundle {
                    access_token: "mock".into(),
                    refresh_token: None,
                    expires_at: None,
                    token_type: "Bearer".into(),
                    scope: None,
                })
                .await
                .expect("mock provider creates without OAuth");
            let page = provider_inst.list_videos(None).await.expect("listing");

            assert!(!page.videos.is_empty(), "{provider}: videos present");
            assert!(!page.files.is_empty(), "{provider}: files present");
            for file in &page.files {
                assert!(
                    file.path.is_some(),
                    "{provider}: fixture {} needs a path for the tree",
                    file.name
                );
            }
            // File ids carry `-f-` so open_stream serves text bytes — and
            // video ids must NOT (the sentinel routes by substring; a video
            // id containing `-f-` would serve text instead of the MP4).
            assert!(page
                .files
                .iter()
                .all(|f| f.provider_file_id.contains("-f-")));
            assert!(page
                .videos
                .iter()
                .all(|v| !v.provider_file_id.contains("-f-")));
        }
    }

